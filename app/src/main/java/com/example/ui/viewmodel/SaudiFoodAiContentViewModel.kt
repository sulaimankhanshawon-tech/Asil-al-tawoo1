private const val TAG = "SaudiFoodAiViewModel"

/**
 * Structured data representation for an authentic localized Saudi food social media template.
 */
data class SaudiFoodContentTemplate(
    val templateTitleAr: String,
    val templateTitleEn: String,
    val saudiDialect: String,
    val targetCity: String,
    val foodTrendCategory: String,
    val captionAr: String,
    val captionEn: String,
    val hashtags: List<String>,
    val callToAction: String,
    val photographyPrompt: String,
    val recommendedPostingTimeSlot: String,
    val targetPlatforms: List<String>,
    val marketingHook: String
)

/**
 * Collection batch of localized Saudi food content templates generated by Firebase AI.
 */
data class SaudiFoodAiContentBatch(
    val trendOverview: String,
    val batchTheme: String,
    val generatedAt: String,
    val templates: List<SaudiFoodContentTemplate>
)

/**
 * Sealed UI State representing Firebase AI generation lifecycle.
 */
sealed interface SaudiFoodAiState {
    data object Idle : SaudiFoodAiState
    data object Loading : SaudiFoodAiState
    data class Streaming(val accumulatedText: String) : SaudiFoodAiState
    data class Success(val batch: SaudiFoodAiContentBatch, val rawJson: String) : SaudiFoodAiState
    data class Error(val message: String) : SaudiFoodAiState
}

/**
 * ViewModel utilizing the Firebase AI SDK (Gemini 3.8 Flash) to synthesize
 * culturally resonant, localized Arabic social media content templates tailored
 * specifically for Saudi Arabian food and restaurant market trends.
 */
class SaudiFoodAiContentViewModel : ViewModel() {

    // 1. JSON Schema for Structured Output using Schema.obj (NOT Schema.object)
    private val singleTemplateSchema = Schema.obj(
        properties = mapOf(
            "templateTitleAr" to Schema.string(description = "عنوان النموذج الإعلاني بالعربية"),
            "templateTitleEn" to Schema.string(description = "English title of the content template"),
            "saudiDialect" to Schema.string(description = "اللهجة السعودية المستخدمة (نجدية، حجازية، شرقية، جنوبية، عامة)"),
            "targetCity" to Schema.string(description = "المدينة السعودية المستهدفة مثل الرياض، جدة، الخبر، مكة"),
            "foodTrendCategory" to Schema.string(description = "تصنيف الترند مثل سماش برجر، كبسة نعيمي، قهوة سعودية"),
            "captionAr" to Schema.string(description = "النص الإعلاني الكامل المكتوب بلهجة سعودية جذابة مع عبارات الكرم والضيافة والرموز التعبيرية"),
            "captionEn" to Schema.string(description = "High quality English counterpart for expatriates and international audiences"),
            "hashtags" to Schema.array(items = Schema.string(), description = "الهاشتاقات المتداولة الأكثر تفاعلاً في السعودية"),
            "callToAction" to Schema.string(description = "الدعوة لاتخاذ إجراء مباشر (طلب، حجز طاولة، زيارة الفرع)"),
            "photographyPrompt" to Schema.string(description = "وصف تصوير فوتوغرافي فائق الواقعية 8K لإنتاج الصورة بواسطة Imagen"),
            "recommendedPostingTimeSlot" to Schema.string(description = "وقت النشر الأنسب بتوقيت مكة/الرياض (Asia/Riyadh UTC+3)"),
            "targetPlatforms" to Schema.array(items = Schema.string(), description = "منصات النشر المثالية مثل Instagram, TikTok, Snapchat, X"),
            "marketingHook" to Schema.string(description = "الزاوية التسويقية الجاذبة للمستهلك السعودي")
        )
    )

    private val contentBatchSchema = Schema.obj(
        properties = mapOf(
            "trendOverview" to Schema.string(description = "تحليل اتجاه ترند الطعام والمطاعم في السوق السعودي"),
            "batchTheme" to Schema.string(description = "الفكرة الرئيسية للمجموعة التسويقية"),
            "templates" to Schema.array(
                items = singleTemplateSchema,
                description = "قائمة النماذج الإعلانية المتوافقة مع الذائقة والثقافة السعودية"
            )
        )
    )

    // 2. Structured Model with Schema Configuration (Lazy Initialization as mandated by Firebase AI Skill)
    private val structuredModel by lazy {
        Firebase.ai.generativeModel(
            modelName = "gemini-3.8-flash",
            generationConfig = generationConfig {
                responseMimeType = "application/json"
                responseSchema = contentBatchSchema
            }
        )
    }

    // 3. Unstructured Streaming Model for Conversational & Real-Time Content Exploration
    private val streamingModel by lazy {
        Firebase.ai.generativeModel(
            modelName = "gemini-3.8-flash"
        )
    }

    private val _uiState = MutableStateFlow<SaudiFoodAiState>(SaudiFoodAiState.Idle)
    val uiState: StateFlow<SaudiFoodAiState> = _uiState.asStateFlow()

    // Recent generated batches history in memory
    private val _historyBatches = MutableStateFlow<List<SaudiFoodAiContentBatch>>(emptyList())
    val historyBatches: StateFlow<List<SaudiFoodAiContentBatch>> = _historyBatches.asStateFlow()

    /**
     * Generates localized Arabic social media marketing templates tailored
     * to a specific Saudi food trend, city, and dialect using Firebase AI Logic.
     */
    fun generateLocalizedTemplates(
        trendKeyword: String,
        targetCity: String = "الرياض",
        preferredDialect: String = "نجدي / سعودي عام",
        category: String = "المطاعم الأكثر رواجاً",
        templateCount: Int = 3
    ) {
        viewModelScope.launch {
            _uiState.value = SaudiFoodAiState.Loading

            val prompt = buildSaudiFoodPrompt(
                trendKeyword = trendKeyword,
                targetCity = targetCity,
                preferredDialect = preferredDialect,
                category = category,
                templateCount = templateCount
            )

            try {
                // Realistic 60s timeout as mandated by Firebase AI Logic skill
                val response = withTimeout(60_000L) {
                    structuredModel.generateContent(prompt)
                }

                val jsonText = response.text
                if (!jsonText.isNullOrBlank()) {
                    // Gemini guarantees valid raw JSON without markdown fences when responseSchema is specified
                    val batch = parseBatchJson(jsonText)
                    _uiState.value = SaudiFoodAiState.Success(batch, jsonText)
                    _historyBatches.value = listOf(batch) + _historyBatches.value
                    Log.d(TAG, "Successfully generated ${batch.templates.size} Saudi food templates.")
                } else {
                    _uiState.value = SaudiFoodAiState.Error("Firebase AI model returned an empty response.")
                }
            } catch (e: TimeoutCancellationException) {
                Log.e(TAG, "Firebase AI generation timed out", e)
                _uiState.value = SaudiFoodAiState.Error(
                    "استغرقت عملية التوليد وقتاً أطول من المتوقع (60 ثانية). يرجى المحاولة مرة أخرى."
                )
            } catch (e: CancellationException) {
                // Must always rethrow CancellationException for cooperative coroutines
                throw e
            } catch (e: Exception) {
                Log.e(TAG, "Firebase AI content generation failed", e)
                _uiState.value = SaudiFoodAiState.Error(
                    e.localizedMessage ?: "فشل في توليد قوالب المحتوى عبر Firebase AI."
                )
            }
        }
    }

    /**
     * Real-time streaming content generation to minimize Time-to-First-Token (TTFT)
     * for interactive ideation sessions.
     */
    fun generateStreamingBrainstorm(
        restaurantConcept: String,
        city: String = "جدة"
    ) {
        viewModelScope.launch {
            _uiState.value = SaudiFoodAiState.Loading
            val accumulated = StringBuilder()

            val streamPrompt = """
                أنت خبير تسويق محتوى مطاعم وأغذية في المملكة العربية السعودية (سفرة AI).
                قم بكتابة أفكار حملات إعلانية مبتكرة باللهجة السعودية لمطعم يقدم: $restaurantConcept في مدينة $city.
                قدم:
                1. الفكرة الإبداعية وزاوية الاستهداف للشباب والعائلات.
                2. نص إعلاني سعودي حماسي لمنصة TikTok و Instagram Reels.
                3. هاشتاقات متصدرة.
                4. أفضل أوقات النشر بتوقيت الرياض.
            """.trimIndent()

            try {
                withTimeout(60_000L) {
                    streamingModel.generateContentStream(streamPrompt).collect { chunk ->
                        val piece = chunk.text.orEmpty()
                        accumulated.append(piece)
                        _uiState.value = SaudiFoodAiState.Streaming(accumulated.toString())
                    }
                }

                if (accumulated.isNotBlank()) {
                    // Create lightweight batch representation from streamed text
                    val batch = SaudiFoodAiContentBatch(
                        trendOverview = "جلسة عصف ذهني سريعة عبر البث الحي",
                        batchTheme = restaurantConcept,
                        generatedAt = formatRiyadhTimestamp(),
                        templates = listOf(
                            SaudiFoodContentTemplate(
                                templateTitleAr = "فكرة تسويقية: $restaurantConcept",
                                templateTitleEn = "Concept: $restaurantConcept",
                                saudiDialect = "سعودي عام",
                                targetCity = city,
                                foodTrendCategory = "عصف ذهني مباشر",
                                captionAr = accumulated.toString(),
                                captionEn = "AI Streamed Saudi Food Campaign Concept",
                                hashtags = listOf("#مطاعم_$city", "#سفرة_AI", "#ترند_السعودية"),
                                callToAction = "اكتشف المزيد",
                                photographyPrompt = "Commercial cinematic lighting food shot of $restaurantConcept in $city",
                                recommendedPostingTimeSlot = "08:00 PM AST",
                                targetPlatforms = listOf("Instagram", "TikTok"),
                                marketingHook = "تجربة طعام استثنائية"
                            )
                        )
                    )
                    _uiState.value = SaudiFoodAiState.Success(batch, accumulated.toString())
                } else {
                    _uiState.value = SaudiFoodAiState.Error("Model returned empty streaming response.")
                }
            } catch (e: TimeoutCancellationException) {
                Log.e(TAG, "Streaming timed out", e)
                _uiState.value = SaudiFoodAiState.Error("انتهت مهلة التوليد الحي بعد 60 ثانية.")
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e(TAG, "Streaming failed", e)
                _uiState.value = SaudiFoodAiState.Error(e.localizedMessage ?: "فشل البث الحي.")
            }
        }
    }

    fun resetState() {
        _uiState.value = SaudiFoodAiState.Idle
    }

    /**
     * Converts a generated template into an application SocialPost model
     * ready to be published or scheduled in Sufra AI.
     */
    fun convertTemplateToSocialPost(
        template: SaudiFoodContentTemplate,
        targetPlatforms: Set<SocialPlatform> = setOf(SocialPlatform.INSTAGRAM, SocialPlatform.TIKTOK)
    ): SocialPost {
        val postId = "post_ai_" + UUID.randomUUID().toString().take(8)
        val imageRes = when {
            template.foodTrendCategory.contains("برجر", ignoreCase = true) || template.captionAr.contains("برجر") ->
                R.drawable.trendy_burger_1793398409429
            template.foodTrendCategory.contains("قهوة", ignoreCase = true) || template.captionAr.contains("قهوة") ->
                R.drawable.saudi_coffee_1793398408663
            else -> R.drawable.hero_kabsa_1793398408425
        }

        return SocialPost(
            id = postId,
            title = template.templateTitleAr,
            captionAr = template.captionAr,
            captionEn = template.captionEn,
            hashtags = template.hashtags,
            targetPlatforms = targetPlatforms,
            scheduledTimeSlot = template.recommendedPostingTimeSlot,
            scheduledDate = "Today",
            status = PostStatus.DRAFT,
            contentType = if (template.targetPlatforms.any { it.contains("TikTok", ignoreCase = true) })
                PostContentType.SHORT_VIDEO_REEL else PostContentType.FOOD_PHOTOGRAPHY,
            imageResId = imageRes,
            imagePrompt = template.photographyPrompt,
            isVideo = template.targetPlatforms.any { it.contains("TikTok", ignoreCase = true) },
            videoDurationSec = 25
        )
    }

    private fun buildSaudiFoodPrompt(
        trendKeyword: String,
        targetCity: String,
        preferredDialect: String,
        category: String,
        templateCount: Int
    ): String {
        return """
            أنت خبير استراتيجي متخصص في صناعة المحتوى والتسويق الرقمي لقطاع الأغذية والمطاعم في المملكة العربية السعودية (Sufra AI).
            
            قم بابتكار عدد $templateCount نماذج محتوى إعلانية متكاملة ومحلية بالكامل، مستوحاة من ترندات الأغذية السعودية الحديثة.
            
            المعطيات:
            - موضوع الترند أو الوجبة: $trendKeyword
            - المدينة السعودية المستهدفة: $targetCity
            - اللهجة السعودية المفضلة: $preferredDialect
            - تصنيف الطعام: $category
            - التوقيت المحلي: بتوقيت مكة المكرمة / الرياض (Asia/Riyadh UTC+3)
            
            متطلبات المحتوى السعودي الأصيل:
            1. استخدم عبارات الترحيب والضيافة السعودية الحقيقية (مثل: يا هلا وغلا، عوافي، حياكم الله، لقمة ما تنشبع، جمعتنا تحلى).
            2. صغ النصوص باللهجة السعودية الطبيعية بعيداً عن الفصحى الجافة أو الترجمات الحرفية.
            3. اذكر اسم المدينة ($targetCity) وأبرز شوارعها أو أجوائها لزيادة التفاعل المحلي.
            4. أضف هاشتاقات متداولة في السعودية (#مطاعم_$targetCity، #ترند_السعودية).
            5. اكتب وصف تصوير دقيق (photographyPrompt) واقعي للمصور أو لنموذج Imagen بدقة 8K مع الإضاءة السينمائية الدافئة.
            6. حدد وقت النشر المثالي المناسب لساعات الذروة السعودية (الغداء 12:00 PM إلى 02:00 PM، العصرية 04:30 PM، العشاء وسهرات الويكند 08:30 PM إلى 11:00 PM).
        """.trimIndent()
    }

    private fun parseBatchJson(jsonText: String): SaudiFoodAiContentBatch {
        val root = JSONObject(jsonText)
        val trendOverview = root.optString("trendOverview", "تحليل ترندات الأغذية السعودية")
        val batchTheme = root.optString("batchTheme", "حملة الأغذية السعودية")
        val templatesJsonArray = root.optJSONArray("templates") ?: JSONArray()

        val templates = mutableListOf<SaudiFoodContentTemplate>()
        for (i in 0 until templatesJsonArray.length()) {
            val item = templatesJsonArray.getJSONObject(i)

            val hashtagsJson = item.optJSONArray("hashtags") ?: JSONArray()
            val hashtags = (0 until hashtagsJson.length()).map { hashtagsJson.getString(it) }

            val platformsJson = item.optJSONArray("targetPlatforms") ?: JSONArray()
            val targetPlatforms = (0 until platformsJson.length()).map { platformsJson.getString(it) }

            templates.add(
                SaudiFoodContentTemplate(
                    templateTitleAr = item.optString("templateTitleAr", "نموذج محتوى سعودي"),
                    templateTitleEn = item.optString("templateTitleEn", "Saudi Food Content Template"),
                    saudiDialect = item.optString("saudiDialect", "سعودي عام"),
                    targetCity = item.optString("targetCity", "الرياض"),
                    foodTrendCategory = item.optString("foodTrendCategory", "المطبخ السعودي"),
                    captionAr = item.optString("captionAr", ""),
                    captionEn = item.optString("captionEn", ""),
                    hashtags = hashtags.ifEmpty { listOf("#مطاعم_السعودية", "#سفرة_AI") },
                    callToAction = item.optString("callToAction", "اطلب الآن عبر الرابط"),
                    photographyPrompt = item.optString("photographyPrompt", "Commercial food photography 8k resolution"),
                    recommendedPostingTimeSlot = item.optString("recommendedPostingTimeSlot", "12:00 PM AST"),
                    targetPlatforms = targetPlatforms.ifEmpty { listOf("Instagram", "TikTok", "X") },
                    marketingHook = item.optString("marketingHook", "أصالة المذاق السعودي")
                )
            )
        }

        return SaudiFoodAiContentBatch(
            trendOverview = trendOverview,
            batchTheme = batchTheme,
            generatedAt = formatRiyadhTimestamp(),
            templates = templates
        )
    }

    private fun formatRiyadhTimestamp(): String {
        val sdf = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)
        sdf.timeZone = TimeZone.getTimeZone("Asia/Riyadh")
        return sdf.format(Date()) + " AST"
    }
